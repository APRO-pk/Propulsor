/// Pick the fit interval that contains `t`.
pub fn fit_for(species: &Species, t: f64) -> &ThermoFit {
    if t < species.fits[1].t_lo {
        &species.fits[0]
    } else {
        &species.fits[1]
    }
}

#[allow(dead_code)]
pub fn species_by_name(name: &str) -> Option<&'static Species> {
    SPECIES.iter().find(|s| s.name == name)
}
