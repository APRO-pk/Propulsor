//! Bundled NASA 7-coefficient (Gordon–McBride) thermodynamic data.
//!
//! Source: McBride, B.J., Zehe, M.J., Gordon, S., NASA/TP-2002-211556
//! ("NASA Glenn Coefficients for Calculating Thermodynamic Properties of
//! Individual Species"). Two temperature intervals are bundled per species
//! (200–1000 K and 1000–6000 K), which covers rocket combustion temperatures.
//!
//! Element indexing: 0=C, 1=H, 2=O, 3=N.

/// A single NASA-curve-fit interval.
#[derive(Debug, Clone, Copy)]
pub struct ThermoFit {
    pub t_lo: f64,
    pub t_hi: f64,
    /// `a1..a7` — exponents `-2,-1,0,1,2,3,4`.
    pub a: [f64; 7],
    /// `b1, b2` — integration constants for h°/RT and s°/R.
    pub b: [f64; 2],
}

/// A species with element composition and two NASA fit intervals.
#[derive(Debug, Clone, Copy)]
pub struct Species {
    pub name: &'static str,
    pub mw: f64,
    /// Atom counts per molecule: [C, H, O, N].
    pub atoms: [u8; 4],
    /// [200–1000 K, 1000–6000 K].
    pub fits: [ThermoFit; 2],
}

